    @PostMapping(value = "/auto-generate-daily-shifts-employee/{company}/{shiftIds}/{override}")
    public Mono<ResponseEntity<Map>> autoGenerateDailyShiftsEmployee(
            @PathVariable(value = "company") final String company,
            @PathVariable(value = "shiftIds") final Collection<UUID> shiftIds,
            @PathVariable(value = "override", required = false) Boolean override,
            @RequestBody Map<String, String> requestBody
    ) {
        log.info("REST request to auto generate daily shifts for company");

        if (override == null) {
            override = false;
        }
        LocalDate date = LocalDate.parse(requestBody.get("date"), DateTimeFormatter.ISO_DATE);
        return shiftService.autoGenerateDailyShiftsEmployee(company, shiftIds, date, override)
                .map(apiResponse -> ResponseEntity.ok().body(apiResponse));
    }


