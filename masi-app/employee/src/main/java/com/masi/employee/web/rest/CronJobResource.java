    private final TimeKeepingViolationService timeKeepingViolationService;
    private final TimeKeepingService timeKeepingService;
    private final ContractCleanupScheduler contractCleanupScheduler;
    private final ZkbioTimeService zkbioTimeService;
    private final ShiftService shiftService;

    @PostMapping("/auto-create-time-keeping-violation")
    public ResponseEntity<Void> timeKeepingViolation() {
        log.info("Time keeping violation cron job started");
        Mono<Void> voidMono = timeKeepingViolationService.generateViolationRecord()
                .doOnError(e -> log.error("Error when generate violation record", e))
                .doAfterTerminate(() -> log.info("Time keeping violation cron job completed"));
        voidMono.subscribe();
        return ResponseEntity.noContent().build();
    }

    @PostMapping("/auto-lock-time-keeping")
    public ResponseEntity<Void> timeKeeping() {
        log.info("Lock time keeping this week cron job started");
        Mono<Void> voidMono = timeKeepingService.lockTimeKeeping().doAfterTerminate(() -> log.info("Time keeping cron job completed"));
        voidMono.subscribe();
        return ResponseEntity.noContent().build();
    }

    @PostMapping("/auto-cleanup-old-deleted-contracts")
    public ResponseEntity<Void> cleanupOldDeletedContracts() {
        log.info("Cleanup old deleted contracts cron job started");
        contractCleanupScheduler.cleanupOldDeletedContracts();
        log.info("Cleanup old deleted contracts cron job completed");
        return ResponseEntity.noContent().build();
    }

    @PostMapping("/auto-update-data-time-keeping")
    public ResponseEntity<Void> updateDataTimeKeeping(@RequestBody Map<String, String> dbCredentials) {
        log.info("Update data time keeping cron job started");
        String urlDb = dbCredentials.get("urlDb");
        String userDb = dbCredentials.get("userDb");
        String pwDb = dbCredentials.get("pwDb");
        ZonedDateTime timeStart = ZonedDateTime.parse(dbCredentials.get("timeStart"));
        ZonedDateTime timeEnd = ZonedDateTime.parse(dbCredentials.get("timeEnd"));
        zkbioTimeService.saveTimeKeeping(urlDb, userDb, pwDb, timeStart, timeEnd)
                .doAfterTerminate(() -> log.info("Update data time keeping cron job completed"))
                .subscribe();
        return ResponseEntity.noContent().build();
    }

    @PostMapping("/auto-update-data-timekeeping-of-employee")
    public ResponseEntity<Void> updateDataTimeKeepingOfEmployee(@RequestBody Map<String, String> dbCredentials) {
        log.info("Update data time keeping cron job started");
        ZonedDateTime timeStart = ZonedDateTime.parse(dbCredentials.get("timeStart"));
        ZonedDateTime timeEnd = ZonedDateTime.parse(dbCredentials.get("timeEnd"));

        Mono<Void> voidMono = zkbioTimeService.updateNameZkbioTime(timeStart, timeEnd)
                .doAfterTerminate(() -> log.info("Time keeping cron job completed"));
        voidMono.subscribe();
        return ResponseEntity.noContent().build();
    }

    @PostMapping("/refresh-data-machine")
    public Mono<ResponseEntity<Void>> tesst() {
        log.info("Update data time keeping cron job started");
        ZonedDateTime TIME_START = ZonedDateTime.now(ZoneId.of("UTC")).minusDays(1);
        ZonedDateTime TIME_END = ZonedDateTime.now(ZoneId.of("UTC"));
        return zkbioTimeService.saveTimeKeeping(null, null, null, TIME_START, TIME_END)
                .then(Mono.just(ResponseEntity.noContent().build()));
    }


